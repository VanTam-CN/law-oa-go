package models

import (
	"errors"
	"time"

	"github.com/google/uuid"
	"gorm.io/gorm"
)

const IntakeSubmissionSnapshotType = "intake_submission"

// ApprovalSnapshot maps the existing immutable approval_snapshots table.
// Historical snapshot types and their source_version values are preserved.
type ApprovalSnapshot struct {
	ID                string    `json:"id" gorm:"type:uuid;primaryKey"`
	ApprovalRequestID string    `json:"approval_request_id" gorm:"type:varchar(36);not null"`
	SnapshotType      string    `json:"snapshot_type" gorm:"type:varchar(80);not null"`
	SnapshotData      string    `json:"snapshot_data" gorm:"type:jsonb;not null"`
	SourceVersion     int       `json:"source_version" gorm:"not null"`
	CreatedAt         time.Time `json:"created_at"`
}

func (ApprovalSnapshot) TableName() string { return "approval_snapshots" }
func (s *ApprovalSnapshot) BeforeCreate(*gorm.DB) error {
	if s.ID == "" {
		s.ID = uuid.NewString()
	}
	return nil
}
func (ApprovalSnapshot) BeforeUpdate(*gorm.DB) error {
	return errors.New("approval snapshots are append-only")
}
func (ApprovalSnapshot) BeforeDelete(*gorm.DB) error {
	return errors.New("approval snapshots are append-only")
}

// ItemID is generated by the service when recording a return, never by a caller.
type SupplementRequest struct {
	ItemID       string `json:"item_id"`
	Category     string `json:"category"`
	FieldKey     string `json:"field_key"`
	PartyLocalID string `json:"party_local_id,omitempty"`
	Description  string `json:"description"`
	Required     bool   `json:"required"`
	Source       string `json:"source,omitempty"`
}
type SupplementResponse struct {
	ItemID   string `json:"item_id"`
	Response string `json:"response"`
}
type ResubmitApprovalRequest struct {
	ExpectedIntakeRevision       string               `json:"expected_intake_revision"`
	ExpectedSubmissionSnapshotID string               `json:"expected_submission_snapshot_id"`
	ReturnRecordID               string               `json:"return_record_id"`
	Responses                    []SupplementResponse `json:"supplement_responses"`
	RevisionNote                 string               `json:"revision_note"`
}
